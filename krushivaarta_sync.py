raw_rows = []

for apmc_id, market_name in apmc_names.items():
    formatted_apmc_name = f"{market_name} बाजार समिती"
    url = "https://www.msamb.com/ApmcDetail/DataGridBind"
    payload = {"apmcCode": apmc_id, "commodityCode": "null"}
    try:
        r = session.post(url, data=payload, headers=headers)
        if r.status_code == 200 and len(r.text.strip()) > 50:
            soup = BeautifulSoup(r.text, "html.parser")
            rows = soup.find_all("tr")
            current_date = ""
            for row in rows:
                date_td = row.find("td", {"colspan": True})
                if date_td:
                    txt = date_td.text.strip()
                    if "/" in txt:
                        current_date = txt
                    continue
                cols = row.find_all(["td", "th"])
                cols_text = [ele.text.strip() for ele in cols]
                if len(cols_text) >= 4:
                    row_data = [current_date, formatted_apmc_name] + cols_text[:7]
                    while len(row_data) < 9:
                        row_data.append("")
                    raw_rows.append(row_data[:9])
    except:
        pass

